// Precompute LLM matches for the mock leads and bake them into
// src/lib/proposalLLMMatches.generated.js, so the Review screen renders real
// LLM-quality matches on mock data — no backend, no DB.
//
// Usage:  ANTHROPIC_API_KEY=sk-ant-... node scripts/llm-precompute-matches.mjs
//         (optional) PROPOSAL_MATCH_MODEL=claude-sonnet-4-6  to trade cost/quality
//
// This calls the SAME prompt + schema the proposal-match edge function uses
// (src/lib/proposalMatchPrompt.js is the shared source of truth), so what you
// see baked here is what production will produce.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { LEADS, UVPS, PAIN_POINTS } from "../src/lib/proposalMockData.js";
import { SYSTEM, MATCH_SCHEMA, MATCH_MODEL_DEFAULT, buildUserContent, normalizeLLMMatch } from "../src/lib/proposalMatchPrompt.js";

const KEY = (process.env.ANTHROPIC_API_KEY || "").trim();
const MODEL = (process.env.PROPOSAL_MATCH_MODEL || MATCH_MODEL_DEFAULT).trim();
// Two modes: call the DEPLOYED edge function (no Anthropic key needed locally —
// the function holds it), or call Anthropic directly with a local key.
const FN_URL = (process.env.PROPOSAL_MATCH_URL || "").trim();
const ANON = (process.env.SUPABASE_ANON_KEY || "").trim();
const VIA_FN = FN_URL && ANON;
if (!VIA_FN && !KEY) {
  console.error("Provide either:\n  PROPOSAL_MATCH_URL=... SUPABASE_ANON_KEY=... node scripts/llm-precompute-matches.mjs   (via deployed fn)\n  ANTHROPIC_API_KEY=sk-ant-... node scripts/llm-precompute-matches.mjs                  (direct)");
  process.exit(1);
}
console.log(VIA_FN ? `Mode: deployed function (${FN_URL})` : `Mode: direct Anthropic (${MODEL})`);

async function matchViaFn(lead) {
  const resp = await fetch(FN_URL, {
    method: "POST",
    headers: { "content-type": "application/json", apikey: ANON, authorization: `Bearer ${ANON}` },
    body: JSON.stringify({ lead, uvps: UVPS, painPoints: PAIN_POINTS }),
  });
  const data = await resp.json().catch(() => ({}));
  if (!resp.ok || data.error) throw new Error(`${resp.status} ${JSON.stringify(data).slice(0, 300)}`);
  return data; // already normalized by the function
}

function extractJSON(text) {
  try { return JSON.parse(text); } catch {}
  const a = text.indexOf("{"), b = text.lastIndexOf("}");
  if (a >= 0 && b > a) { try { return JSON.parse(text.slice(a, b + 1)); } catch {} }
  return null;
}

async function matchOne(lead) {
  const resp = await fetch("https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers: { "x-api-key": KEY, "anthropic-version": "2023-06-01", "content-type": "application/json" },
    body: JSON.stringify({
      model: MODEL,
      max_tokens: 2000,
      system: SYSTEM,
      output_config: { format: { type: "json_schema", schema: MATCH_SCHEMA } },
      messages: [{ role: "user", content: buildUserContent(lead, { uvps: UVPS, painPoints: PAIN_POINTS }) }],
    }),
  });
  if (!resp.ok) throw new Error(`${resp.status} ${(await resp.text()).slice(0, 300)}`);
  const data = await resp.json();
  const text = (data.content || []).filter((b) => b.type === "text").map((b) => b.text).join("");
  const raw = extractJSON(text);
  if (!raw) throw new Error(`unparseable output: ${text.slice(0, 200)}`);
  return normalizeLLMMatch(raw, { uvps: UVPS });
}

const out = {};
for (const lead of LEADS) {
  process.stdout.write(`Matching ${lead.id} (${lead.community})… `);
  try {
    const m = VIA_FN ? await matchViaFn(lead) : await matchOne(lead);
    out[lead.id] = m;
    console.log(`ok — ${m.match}% overall, ${m.concerns.length} concerns`);
  } catch (e) {
    console.log(`FAILED: ${e.message}`);
  }
}

const header = `// GENERATED by scripts/llm-precompute-matches.mjs (model: ${MODEL}). Do not edit by hand.
// Re-run with ANTHROPIC_API_KEY set to refresh. Empty {} → deterministic fallback.
export const LLM_MATCHES = `;
const dir = dirname(fileURLToPath(import.meta.url));
const target = join(dir, "../src/lib/proposalLLMMatches.generated.js");
writeFileSync(target, header + JSON.stringify(out, null, 2) + ";\n");
console.log(`\nWrote ${Object.keys(out).length} match(es) → src/lib/proposalLLMMatches.generated.js`);
